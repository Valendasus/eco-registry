export function feminineSurname(surname: string) {
  if (surname.endsWith('ский')) return `${surname.slice(0, -2)}ая`
  if (/(ов|ев|ёв|ин|ын)$/.test(surname)) return `${surname}а`
  return surname
}

export function masculineSurname(surname: string) {
  if (surname.endsWith('ская')) return `${surname.slice(0, -2)}ий`
  if (/(ова|ева|ёва|ина|ына)$/.test(surname)) return surname.slice(0, -1)
  return surname
}

export const surnameFor = (surname: string, gender: 'male' | 'female') =>
  gender === 'male' ? masculineSurname(surname) : feminineSurname(masculineSurname(surname))
